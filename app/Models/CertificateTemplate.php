<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\Relations\HasMany;
use Illuminate\Support\Str;

class CertificateTemplate extends Model
{
    use HasFactory;

    protected $fillable = [
        'name',
        'slug',
        'orientation',
        'background_image',
        'valid_for_months',
        'canvas_width',
        'canvas_height',
        'elements',
        'custom_css',
        'custom_html',
        'is_default',
        'is_active',
        'issued_count',
        'created_by',
    ];

    protected $casts = [
        'elements' => 'array',
        'is_default' => 'boolean',
        'is_active' => 'boolean',
        'valid_for_months' => 'integer',
        'canvas_width' => 'integer',
        'canvas_height' => 'integer',
        'issued_count' => 'integer',
    ];

    protected static function booted()
    {
        static::creating(function ($template) {
            if (empty($template->slug)) {
                $template->slug = Str::slug($template->name) . '-' . Str::random(5);
            }
        });

        static::saving(function ($template) {
            if ($template->is_default) {
                // Ensure only one template is marked as default
                static::where('id', '!=', $template->id)->update(['is_default' => false]);
            }
        });
    }

    public function courses(): HasMany
    {
        return $this->hasMany(Course::class);
    }

    public function creator(): BelongsTo
    {
        return $this->belongsTo(User::class, 'created_by');
    }

    /**
     * Get the active default template
     */
    public static function getDefault(): ?self
    {
        return static::where('is_default', true)->where('is_active', true)->first()
            ?? static::where('is_active', true)->first();
    }

